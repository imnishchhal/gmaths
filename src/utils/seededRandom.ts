/**
 * Deterministic PRNG (FNV-1a hash + Mulberry32) used for reproducible
 * Admin-seeded Daily Challenge math drills.
 */

export function hashSeedString(seed: string): number {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function createSeededRng(seed: string): () => number {
  let state = hashSeedString(seed) || 0x6d2b79f5;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function getTodayDailySeedKey(adminSeed: string, indianClass: string): string {
  const now = new Date();
  const y = now.getFullYear();
  const m = String(now.getMonth() + 1).padStart(2, '0');
  const d = String(now.getDate()).padStart(2, '0');
  const cleanSeed = (adminSeed || 'DAILY-2026').trim();
  return `${cleanSeed}::${y}-${m}-${d}::${indianClass}`;
}
